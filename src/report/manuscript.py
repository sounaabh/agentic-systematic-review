"""Report Agent: assembles the final review (Markdown), PRISMA diagram, BibTeX and CSV tables."""
import csv
import re
import time

from src.audit import log, run_dir
from src.config import CONFIG
from src.report.prisma import draw_prisma
from src.state import ReviewState


def _bibkey(rec: dict, key: str) -> str:
    author = re.sub(r"[^A-Za-z]", "", (rec.get("authors") or ["anon"])[0].split()[-1]) or "anon"
    return f"{author}{rec.get('year') or ''}{key}"


def _bibtex(studies: list[dict]) -> str:
    out = []
    for s in studies:
        r = s["record"]
        fields = {"title": r["title"], "author": " and ".join(r.get("authors") or []),
                  "year": r.get("year"), "journal": r.get("venue"), "doi": r.get("doi"), "url": r.get("url")}
        body = ",\n".join(f"  {k} = {{{v}}}" for k, v in fields.items() if v)
        out.append(f"@article{{{_bibkey(r, s['key'])},\n{body}\n}}")
    return "\n\n".join(out)


def _md_table(rows: list[list], header: list[str]) -> str:
    clean = lambda x: str(x if x is not None else "").replace("|", "/").replace("\n", " ")
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(clean(c) for c in r) + " |" for r in rows]
    return "\n".join(lines)


def report_agent(state: ReviewState) -> ReviewState:
    run_id, d = state["run_id"], run_dir(state["run_id"])
    p, pr, m = state["protocol"], state["prisma"], state["metrics"]
    draw_prisma(pr, d / "prisma.png")

    rec_by_key = {s["key"]: s["record"] for s in state["studies"]}
    qual = {q["key"]: q for q in state["quality"]}
    incl = [e for e in state["extractions"] if e.get("eligible_confirmed", True)]

    char_rows = [[e["key"], f"{(rec_by_key[e['key']].get('authors') or ['?'])[0]} ({rec_by_key[e['key']].get('year')})",
                  e.get("study_type"), e.get("sample_or_dataset"), e.get("ai_method"),
                  e.get("effect_direction"), qual.get(e["key"], {}).get("overall"),
                  ", ".join(e.get("evidence", []))] for e in incl]
    qa_items = ["clear_aims", "appropriate_design", "adequate_sample_or_data", "valid_outcome_measures",
                "limitations_addressed", "overall"]
    qa_rows = [[q["key"]] + [q.get(i, "") for i in qa_items] for q in state["quality"]]

    with open(d / "extraction_table.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        cols = ["key", "title", "study_type", "setting", "sample_or_dataset", "ai_method", "comparison",
                "outcomes", "key_findings", "effect_direction", "limitations", "evidence", "full_text"]
        w.writerow(cols)
        for e in state["extractions"]:
            w.writerow([", ".join(e[c]) if isinstance(e.get(c), list) else e.get(c, "") for c in cols])
    (d / "references.bib").write_text(_bibtex(state["studies"]), encoding="utf-8")

    critic_log = "\n".join(
        f"- Revision {c['revision']}: {'approved' if c['approved'] else 'revision requested'}"
        + "".join(f"\n  - {i}" for i in c["issues"]) for c in state.get("critic_feedback", []))
    refs = "\n".join(
        f"- **[{s['key']}]** {', '.join((s['record'].get('authors') or [])[:3])}"
        f"{' et al.' if len(s['record'].get('authors') or []) > 3 else ''} ({s['record'].get('year')}). "
        f"*{s['record']['title']}*. {s['record'].get('venue') or ''}. "
        f"{'https://doi.org/' + s['record']['doi'] if s['record'].get('doi') else s['record'].get('url', '')}"
        for s in state["studies"])
    sources = ", ".join(pr.get("identified", {}).keys())
    n_inc = pr.get("included_final", 0)
    queries = "\n".join(f"  - `{q}`" for q in state["search_strategy"]["queries"])

    md = f"""# Systematic Review: {p['research_question']}

*Automatically generated by the sr-agent multi-agent pipeline on {time.strftime('%Y-%m-%d')} (run `{run_id}`).
All decisions are logged in `audit.jsonl`. This draft must be checked by human reviewers.*

## 1. Methods

**Protocol (PICOC).** Population: {p['population']}. Intervention: {p['intervention']}.
Comparator: {p['comparator']}. Outcomes: {', '.join(p['outcomes'])}. Context: {p['context']}.
Eligible designs: {', '.join(p['study_designs'])}. Years: {p.get('year_from')}-present.

**Inclusion criteria:**
{chr(10).join('- ' + c for c in p['inclusion_criteria'])}

**Exclusion criteria:**
{chr(10).join('- ' + c for c in p['exclusion_criteria'])}

**Information sources and search.** Databases: {sources}. Search date: {time.strftime('%Y-%m-%d')}. Queries:
{queries}

**Selection process.** Records were deduplicated (DOI, PMID and fuzzy title matching), then screened on
title and abstract by two independent LLM reviewers ({m.get('screener_a_model')} and {m.get('screener_b_model')})
with different prompts. Disagreements and uncertain cases were resolved by an adjudicator agent.

**Data extraction.** Open-access full texts were retrieved when available (otherwise the abstract was used),
split into passages and searched with {m.get('retrieval_mode', 'BM25 keyword retrieval')}.
Each extracted value cites the passage ids it was taken from.

**Quality appraisal.** A simplified checklist inspired by the Mixed Methods Appraisal Tool (MMAT).

**Synthesis.** Narrative synthesis following SWiM, reviewed by a critic agent
({len(state.get('critic_feedback', []))} review round(s)). No meta-analysis was performed.

## 2. Results

### 2.1 Study selection

![PRISMA 2020 flow diagram](prisma.png)

{pr.get('identified_total')} records were identified, {pr.get('duplicates_removed')} duplicates removed and
{pr.get('screened')} records screened. Inter-reviewer agreement: Cohen's kappa = {m.get('screening_kappa')}
(raw agreement {m.get('screening_raw_agreement')}; {m.get('screening_conflicts')} records adjudicated).
{n_inc} {'study was' if n_inc == 1 else 'studies were'} included ({pr.get('full_text_retrieved')} with full text).

### 2.2 Study characteristics

{_md_table(char_rows, ['Key', 'Study', 'Design', 'Sample / data', 'AI method', 'Effect', 'Quality', 'Evidence'])}

### 2.3 Quality appraisal

{_md_table(qa_rows, ['Key', 'Clear aims', 'Design', 'Sample/data', 'Outcome measures', 'Limitations', 'Overall'])}

### 2.4 Synthesis

{state['synthesis']}

## 3. Limitations of this automated review

- Screening and extraction were performed by language models ({m.get('screener_a_model')}); errors are possible
  and every decision should be verified by a human (see `screening.json`, `extractions.json`).
- Only open-access full texts were used; {pr.get('abstract_only', 0)} included studies were assessed on abstract only.
- Search was limited to {sources} and capped at {CONFIG['search']['max_records_to_screen']} records for screening.
- Quality appraisal used a simplified checklist, not a validated full tool.
- Traceability: {int((m.get('traceability_rate') or 0) * 100)}% of extracted studies cite at least one supporting passage.

## 4. Critic agent log

{critic_log}

## References

{refs}
"""
    path = d / "review.md"
    path.write_text(md, encoding="utf-8")
    log(run_id, "report", "report_written", {"path": str(path), "metrics": m, "prisma": pr})
    return {"report_path": str(path)}
